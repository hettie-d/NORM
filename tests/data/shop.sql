-- Three-level app schema for the tests: customer -> orders -> order_line, plus
-- a lookup table (tier) and a many-to-one reference (order_line -> product).
create schema norm_shop;

create table norm_shop.tier (tier_id int primary key, tier_name text not null);
create table norm_shop.product (product_id int primary key, product_name text not null, unit_price numeric(10, 2));

create table norm_shop.customer (
    customer_id int generated by default as identity primary key,
    name text not null,
    tier_id int references norm_shop.tier,
    joined date
);
create table norm_shop.orders (
    order_id int generated by default as identity primary key,
    customer_id int references norm_shop.customer,
    order_name text,
    placed timestamptz
);
create table norm_shop.order_line (
    line_id int generated by default as identity primary key,
    order_id int references norm_shop.orders,
    product_id int references norm_shop.product,
    qty int
);

